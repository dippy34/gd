RES = Path(__file__).resolve().parent.parent/'research'
def load_names():
    m = {}
    for line in (RES/'objectids.yml').read_text().splitlines():
        if ':' not in line: continue
        k, v = line.rsplit(':', 1)
        k = k.strip(); v = v.strip()
        if not v.lstrip('-').isdigit(): continue
        i = int(v)
        k = k.replace('.png','').replace('_001','')
        m.setdefault(i, []).append(k)
    return {k: '/'.join(sorted(set(v))) for k, v in m.items()}
